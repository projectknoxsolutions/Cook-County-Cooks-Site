let imBinary;   // resolved lazily so a run that re-encodes nothing needs no IM

function imagemagick() {
  if (imBinary !== undefined) return imBinary;
  for (const [bin, pre] of [['magick', ['convert']], ['convert', []]]) {
    const r = spawnSync(bin, [...pre, '-version'], { encoding: 'utf8' });
    if (!r.error && r.status === 0) { imBinary = { bin, pre }; return imBinary; }
  }
  imBinary = null;
  return null;
}

/**
 * Re-encode one deck photograph down to the frame it lands in.
 * `sha` is over the WebP that comes out, not over the JPEG that went in — see
 * `photoFileStamp` below for why that distinction is the whole point.
 * @returns {{bytes:Buffer, w:number, h:number, sha:string}}
 */
function encodePhoto(srcBuf, key) {
  const im = imagemagick();
  if (!im) {
    fail(`ImageMagick not found, and "${key}" needs its photograph re-encoded. ` +
         `A 1024x1536 deck JPEG must never be committed straight into a picture ` +
         `frame ~105px wide. Install imagemagick (the workflow installs it when missing; ` +
         `it) or run with the photo already on disk. Nothing written.`);
  }
  const tmpIn  = join(tmpdir(), `ccc-hc-${process.pid}-${key}.src`);
  const tmpOut = join(tmpdir(), `ccc-hc-${process.pid}-${key}.webp`);
  try {
    writeFileSync(tmpIn, srcBuf);
    const args = [
      ...im.pre, tmpIn,
      '-auto-orient',
      '-strip',                                    // EXIF, GPS, colour profiles
      '-resize', `${PHOTO_MAX_W}x${PHOTO_MAX_H}>`, // shrink only, keep aspect
      '-quality', String(PHOTO_QUALITY),
      '-define', 'webp:method=6',
      tmpOut
    ];
    const r = spawnSync(im.bin, args, { encoding: 'utf8' });
    if (r.error || r.status !== 0 || !existsSync(tmpOut)) {
      fail(`${key}: photo re-encode failed — ${(r.stderr || (r.error && r.error.message) || 'unknown').trim()}`);
    }
    const bytes = readFileSync(tmpOut);

    // `convert <file> -format '%w %h' info:` works on ImageMagick 6 and 7 alike,
    // so the dimensions come back without needing a second binary on PATH.
    const id = spawnSync(im.bin, [...im.pre, tmpOut, '-format', '%w %h', 'info:'], { encoding: 'utf8' });
    let w = 0; let h = 0;
    if (!id.error && id.status === 0) {
      const parts = String(id.stdout).trim().split(/\s+/);
      w = Number(parts[0]) || 0; h = Number(parts[1]) || 0;
    }
    if (!w || !h) fail(`${key}: could not read the re-encoded photo's dimensions.`);
    return { bytes, w, h, sha: sha256(bytes) };
  } finally {
    for (const f of [tmpIn, tmpOut]) { try { if (existsSync(f)) unlinkSync(f); } catch {} }
  }
}

/**
 * THE HASH OF THE FILE THE WEBSITE ACTUALLY DOWNLOADS.
 *
 * `photo_sha` — which stays exactly as it is, because the website reads it
 * today — is the hash of the DECK'S SOURCE image: the 1024x1536 JPEG that came
 * out of the slide. The file the browser fetches is the WebP this script wrote,
 * and those are two different sets of bytes. Verified 2026-09-04: not one
 * committed photo's sha256 equals its recorded `photo_sha`. Every one of them.
 *
 * That matters because the website appends the stamp as `?v=` to cache-bust a
 * filename that never changes (photos/big-south.webp is always that name). A
 * stamp that does not track the served bytes cannot do that job, and there are
 * two ordinary paths that rewrite a photograph WITHOUT moving `photo_sha` at
 * all: the file going missing from disk (which re-encodes from an unchanged
 * source), and any change to PHOTO_MAX_W / PHOTO_MAX_H / PHOTO_QUALITY (which
 * re-encodes every photograph in the repo from unchanged sources). In both, the
 * browser keeps serving the old picture out of its cache indefinitely.
 *
 * So `photo_file_sha` is added ALONGSIDE `photo_sha`, never in place of it: the
 * website is not being changed in this pass, and a field it does not know about
 * cannot hurt it. It is read straight off the bytes on disk rather than
 * remembered from the last run, because the point of it is to describe what is
 * THERE — including the case where the last run's record is the thing that is
 * wrong.
 *
 * @returns {{sha:string, bytes:number}|null}
 */
function photoFileStamp(name) {
  try {
    const buf = readFileSync(join(PHOTO_DIR, name));
    return { sha: sha256(buf), bytes: buf.length };
  } catch {
    return null;
  }
}

/* ---------------------------------------------------------------------------
 * 9. THE PREVIOUS FILE
 * ------------------------------------------------------------------------ */

function readPrevious() {
  const empty = { districtOrder: [], districts: {}, chefs: {}, sources: {} };
  if (!existsSync(OUT_JSON)) return empty;
  let doc;
  try { doc = JSON.parse(readFileSync(OUT_JSON, 'utf8')); }
  catch (err) {
    console.warn(`! headchefs.json is not valid JSON (${err.message}); rebuilding from the decks.`);
    return empty;
  }
  const districts = (doc && doc.districts) || {};
  const chefs = {};
  for (const c of (doc && Array.isArray(doc.headchefs) ? doc.headchefs : [])) {
    // Tolerate the hand-made 2026-08-26 snapshot, which had no district keys:
    // re-derive one from its slide_title so its entries can be held over.
    let key = c && c.district_key;
    if (!key && c && c.slide_title) {
      const deck = DECKS.find((d) => d.label === c.region_deck) || DECKS[0];
      key = districtFromTitle(c.slide_title, deck, !!c.is_xfinity).key;
    }
    if (key) chefs[key] = c;
  }
  const order = Array.isArray(doc && doc.district_order) && doc.district_order.length
    ? doc.district_order.slice()
    : [];
  // MIGRATION. The hand-made 2026-08-26 snapshot carried no per-entry clocks, so
  // every held entry would read as infinitely old and be dropped on the first
  // run — blanking frames on the very run that was supposed to stop that. The
  // document's own `generated_at` is when those entries were last confirmed.
  const fileStamp = (doc && doc.generated_at) || null;
  if (fileStamp) {
    for (const c of Object.values(chefs)) if (!c.last_confirmed) c.last_confirmed = fileStamp;
    for (const d of Object.values(districts)) if (!d.last_confirmed) d.last_confirmed = fileStamp;
  }
  // The per-deck record of the LAST run: how many head-chef slides each deck
  // yielded, and when. This is what tells a deck that has always had chefs and
  // suddenly has none apart from a deck that has legitimately never had any.
  const sources = {};
  for (const src of (doc && Array.isArray(doc.sources) ? doc.sources : [])) {
    if (src && src.deck) sources[src.deck] = src;
  }
  return { districtOrder: order, districts, chefs, sources };
}

/**
 * Everything that decides whether an entry actually CHANGED.
 *
 * `photo_file_sha` is in here as well as `photo_sha` deliberately: the two
 * answer different questions. `photo_sha` moves when the CLIENT changes the
 * photograph; `photo_file_sha` moves when the bytes the visitor downloads
 * change for any reason at all, including a re-encode from an unchanged source
 * after PHOTO_QUALITY was tuned. The second is the one a browser cache can see,
 * so leaving it out would mean an entry whose served picture changed being
 * stamped "last_changed: <last week>".
 */
function contentFingerprint(chef) {
  return sha256(Buffer.from(JSON.stringify([
    chef.name, chef.store_role, chef.writeup, chef.stats,
    chef.is_xfinity, chef.slide_title, chef.photo_sha || null,
    chef.photo_file_sha || null, !!chef.is_store, !!chef.photo_low_quality
  ]), 'utf8'));
}

/* ---------------------------------------------------------------------------
 * 10. THE RUN
 * ------------------------------------------------------------------------ */

async function run() {
  const started = nowIso();
  const prev = readPrevious();

  /* -- 10a. read every deck BEFORE deciding anything ----------------------- */
  const sources = [];
  const found = new Map();        // district key -> slide

  for (const deck of DECKS) {
    process.stdout.write(`· ${deck.key}: fetching ${deck.raw}\n`);
    const html = await fetchDeck(deck);
    const prevSrc = prev.sources[deck.key] || null;
    const prevFromDeck = Object.values(prev.districts)
      .filter((d) => d && d.source_deck === deck.key).length;
    const slides = extractSlides(html, deck, {
      had: !!((prevSrc && Number(prevSrc.head_chef_slides) > 0) || prevFromDeck > 0),
      slides: prevSrc ? Number(prevSrc.head_chef_slides) || 0 : prevFromDeck,
      when: prevSrc ? prevSrc.fetched_at : null,
      // The district NAMES from the last run, so the partial-harvest guard can
      // tell somebody WHICH districts vanished rather than only how many.
      districts: (prevSrc && Array.isArray(prevSrc.districts)) ? prevSrc.districts : []
    });
    process.stdout.write(
      `  ${(html.length / 1048576).toFixed(2)} MB, ${slides.length} head-chef slide` +
      `${slides.length === 1 ? '' : 's'}${slides.length ? ': ' + slides.map((s) => `${s.district.district} / ${s.name}`).join(', ') : ''}\n`);

    for (const s of slides) {
      if (found.has(s.district.key)) {
        // Two slides claiming one district: the LAST one in the deck wins, which
        // is how these decks are edited (a new slide appended, the old left in).
        console.warn(`  ! two slides for "${s.district.district}" in ${deck.key}; ` +
                     `using the later one (${s.name}).`);
      }
      found.set(s.district.key, s);
      if (VERBOSE) {
        console.log(`    title="${s.slideTitle}" district="${s.district.district}" ` +
                    `name="${s.name}" role="${s.storeRole}" stats=${s.stats.length} ` +
                    `writeup=${s.writeup.length}ch photo=${s.photo ? s.photo.buf.length + 'B' : 'none'}`);
      }
    }

    sources.push({
      deck: deck.key,
      label: deck.label,
      page: deck.page,
      raw: deck.raw,
      fetched_at: nowIso(),
      bytes: html.length,
      head_chef_slides: slides.length,
      districts: slides.map((s) => s.district.district)
    });
  }

  /* -- 10b. the roster: persisted order, seeded once, extended by the decks - */
  const order = prev.districtOrder.slice();
  if (!order.length) for (const s of SEED_ROSTER) order.push(s.key);
  for (const key of found.keys()) if (!order.includes(key)) order.push(key);

  const seedByKey = new Map(SEED_ROSTER.map((s) => [s.key, s]));

  /* -- 10b-i. a district key nobody has ever seen -------------------------- *
   * The EARLY SIGNAL that a slide title was reworded. It is not an error on its
   * own — the header is explicit that the title IS the district and a rename
   * follows by itself — but it is the one moment somebody can add an ALIASES
   * line and keep the rename cosmetic instead of structural. Printed on every
   * run it happens, whether or not the wall is over capacity.                */
  const known = new Set([...prev.districtOrder, ...SEED_ROSTER.map((r) => r.key)]);
  const newcomers = [...found.keys()].filter((k) => !known.has(k));
  // The district key IS the ALIASES key: both are slug() of the district text,
  // and slug(titleCase(x)) === slug(x). So the key can be pasted straight in.
  for (const key of newcomers) {
    const s = found.get(key);
    console.warn(`  ! new district key "${key}" ("${s.district.district}") from ${s.deck} ` +
                 `slide "${s.slideTitle}" — never seen before. If that is a RENAME of a ` +
                 `district already on the wall, add '${key}': '<the district it used to be>' ` +
                 `to ALIASES in this file, so the existing frame follows the rename instead ` +
                 `of a seventh district appearing.`);
  }

  /* -- 10b-ii. more districts than the wall has frames --------------------- *
   * A build failure, not a browser console warning. See CHEF_FRAME_FALLBACK
   * above for the measurement and the reproduction. Nothing has been written at
   * this point, so the wall keeps its last good state while somebody reads
   * this — the same fail-soft contract as every other guard in here.         */
  const FRAMES = readFrameCount();
  if (order.length > FRAMES) {
    const overflow = order.slice(FRAMES);
    const describe = (k) => {
      const s = found.get(k);
      return s ? `"${s.district.district}" [${k}] — ${s.deck} slide "${s.slideTitle}"`
               : `"${k}" (held from headchefs.json; not in a deck this run)`;
    };
    const renameHint = (newcomers.length ? newcomers : ['<slug-of-the-new-title>'])
      .map((k) => `      '${k}': '<the district this slide used to be>',`).join('\n');

    fail(
      `${order.length} districts on the roster but the break-room wall has ${FRAMES} painted ` +
      `frames (CHEF_FRAMES in rooms.js).\n` +
      `  Past ${FRAMES}, chefwall.js drops the overflow with a console warning nobody reads — and ` +
      `the roster is persisted-first, so the one it drops is the NEWCOMER: the district that is ` +
      `actually in the deck right now, while its frame shows a held, stale chef.\n` +
      `  Over capacity: ${overflow.map(describe).join('; ')}\n` +
      (newcomers.length
        ? `  Never seen before: ${newcomers.map(describe).join('; ')}\n`
        : `  No new district keys this run — the roster in headchefs.json is already over capacity.\n`) +
      `  If a slide title was REWORDED, fold it back onto the district it already is, in ALIASES ` +
      `in this file:\n${renameHint}\n` +
      `  If it is genuinely a seventh district, a seventh frame has to be painted into rooms.js ` +
      `CHEF_FRAMES first — that is an art-direction change, and the wall cannot show more chefs ` +
      `than it has frames.`
    );
  }

  /* -- 10c. build one entry per district in the roster --------------------- */
  const now = Date.now();
  const chefs = [];
  const districts = {};
  const photos = new Map();       // filename -> Buffer, staged, written at the end
  const dropped = [];
  const held = [];
  const changed = [];

  for (const key of order) {
    const slide = found.get(key);
    const prevChef = prev.chefs[key] || null;
    const prevMeta = prev.districts[key] || null;

    /* --- present in a deck right now ------------------------------------ */
    if (slide) {
      const photoName = slide.photo ? `${key}.webp` : null;
      let photoFile = null; let photoW = 0; let photoH = 0; let photoBytes = 0;
      let photoSha = null; let photoFileSha = null;

      if (slide.photo) {
        photoSha = slide.photo.sha;
        const onDisk = existsSync(join(PHOTO_DIR, photoName));
        const sameSource = prevChef && prevChef.photo_sha === photoSha && onDisk;
        if (sameSource) {
          // Byte-identical source and the file is already there. Do NOT
          // re-encode: two ImageMagick builds do not produce identical bytes,
          // and a re-encode every 30 minutes would be a commit every 30 minutes
          // for a photograph nobody changed.
          photoFile = `photos/${photoName}`;
          photoW = Number(prevChef.photo_w) || 0;
          photoH = Number(prevChef.photo_h) || 0;
          // Read the size and the hash off the FILE rather than carrying last
          // run's numbers forward. It costs one ~15 KB read and it is the only
          // way `photo_file_sha` can describe the bytes that are really there —
          // including on the run after PHOTO_QUALITY was changed, where the
          // source is identical and the served picture is not.
          const stamp = photoFileStamp(photoName);
          photoBytes = stamp ? stamp.bytes : 0;
          photoFileSha = stamp ? stamp.sha : null;
        } else {
          const enc = encodePhoto(slide.photo.buf, key);
          photos.set(photoName, enc.bytes);
          photoFile = `photos/${photoName}`;
          photoW = enc.w; photoH = enc.h; photoBytes = enc.bytes.length;
          photoFileSha = enc.sha;
          if (VERBOSE) {
            console.log(`    photo ${key}: ${slide.photo.buf.length}B source -> ` +
                        `${enc.bytes.length}B webp ${enc.w}x${enc.h}`);
          }
        }
      }

      // Reported, never enforced — see PHOTO_MIN_W / PHOTO_MIN_H.
      const lowQuality = !!photoFile && isLowQualityPhoto(photoW, photoH);
      if (lowQuality) {
        console.warn(`  ! ${slide.district.district}: the photograph on this slide is ` +
                     `${photoW}x${photoH}, below the ${PHOTO_MAX_W}x${PHOTO_MAX_H} the picture ` +
                     `frame is drawn for` + (photoW > photoH ? ' and landscape in a portrait frame' : '') +
                     `. That is what the deck carries, so it is published as-is and flagged ` +
                     `photo_low_quality — it is not an error and nothing is dropped for it.`);
        annotate(`${slide.district.district}: low-resolution portrait`,
                 `${slide.name}'s photograph is ${photoW}x${photoH}` +
                 (photoW > photoH ? ' (landscape, in a portrait frame)' : '') +
                 `. Published as-is and flagged photo_low_quality.`);
      }

      const entry = {
        district: slide.district.district,
        district_key: key,
        district_short: slide.district.short,
        region_deck: slide.deckLabel,
        slide_title: slide.slideTitle,
        slide_index: slide.slideIndex,
        name: slide.name,
        store_role: slide.storeRole,
        stats: slide.stats,
        writeup: slide.writeup,
        is_xfinity: slide.isXfinity,
        // A store can legitimately win — see deriveIsStore. This is a signal for
        // the wall, not a filter, and nothing downstream has to read it.
        is_store: deriveIsStore(slide.storeRole),
        vacant: false,
        has_photo: !!photoFile,
        photo_file: photoFile,
        photo_w: photoW,
        photo_h: photoH,
        photo_bytes: photoBytes,
        photo_sha: photoSha,
        // The hash of the WebP that is actually served, next to (never instead
        // of) the hash of the deck's source image — see photoFileStamp.
        photo_file_sha: photoFileSha,
        photo_low_quality: lowQuality
      };

      const fp = contentFingerprint(entry);
      const prevFp = prevChef ? contentFingerprint(prevChef) : null;
      entry.last_confirmed = started;
      entry.last_changed = (prevChef && prevFp === fp && prevChef.last_changed)
        ? prevChef.last_changed
        : started;
      entry.days_since_confirmed = 0;
      entry.stale = false;
      if (prevFp !== fp) changed.push(`${entry.district}: ${entry.name}`);

      chefs.push(entry);
      districts[key] = {
        district: entry.district,
        district_short: entry.district_short,
        source_deck: slide.deck,
        source_url: DECKS.find((d) => d.key === slide.deck).page,
        slide_title: entry.slide_title,
        present_this_run: true,
        first_seen: (prevMeta && prevMeta.first_seen) || started,
        last_confirmed: started,
        last_changed: entry.last_changed,
        days_since_confirmed: 0
      };
      continue;
    }

    /* --- absent from every deck this run -------------------------------- */
    const label = (prevChef && prevChef.district) || (prevMeta && prevMeta.district)
                || (seedByKey.get(key) && seedByKey.get(key).district) || titleCase(key.replace(/-/g, ' '));
    const shortLabel = (prevChef && prevChef.district_short) || (prevMeta && prevMeta.district_short)
                || (seedByKey.get(key) && seedByKey.get(key).short) || label;

    const lastConfirmed = (prevChef && prevChef.last_confirmed)
                       || (prevMeta && prevMeta.last_confirmed) || null;
    const ageDays = lastConfirmed ? (now - Date.parse(lastConfirmed)) / DAY_MS : Infinity;

    if (prevChef && prevChef.name && ageDays <= STALE_DROP_DAYS) {
      // HOLD LAST-SEEN. The chef stays on the wall; only the clock moves.
      const heldEntry = Object.assign({}, prevChef, {
        district: label,
        district_key: key,
        district_short: shortLabel,
        // Held entries predate these fields, so they are derived rather than
        // carried: an entry that has been holding since before this change would
        // otherwise be the only one on the wall missing its store flag.
        is_store: prevChef.is_store === undefined
          ? deriveIsStore(prevChef.store_role)
          : !!prevChef.is_store,
        vacant: false,
        days_since_confirmed: Math.round(ageDays * 10) / 10,
        stale: ageDays >= STALE_WARN_DAYS,
        last_confirmed: lastConfirmed,
        last_changed: prevChef.last_changed || lastConfirmed
      });

      /* LEGACY PHOTO MIGRATION. A held entry can still be pointing at a photo
         from the hand-made snapshot — an un-resized JPEG under a name this
         script does not own (e.g. photos/chicago-3.jpg, 43 KB). We no longer
         have its slide, but we have the file, so it is re-encoded from disk
         into this district's own photos/<key>.webp and brought inside the byte
         budget. Runs once: after the first migration the name already matches
         and nothing happens. */
      const want = `photos/${key}.webp`;
      let justEncoded = false;
      if (heldEntry.photo_file && heldEntry.photo_file !== want) {
        const from = join(PHOTO_DIR, String(heldEntry.photo_file).replace(/^photos\//, ''));
        if (existsSync(from)) {
          const enc = encodePhoto(readFileSync(from), key);
          photos.set(`${key}.webp`, enc.bytes);
          heldEntry.photo_file = want;
          heldEntry.photo_w = enc.w; heldEntry.photo_h = enc.h;
          heldEntry.photo_bytes = enc.bytes.length;
          heldEntry.photo_sha = null;   // the deck source is gone; nothing to match
          heldEntry.photo_file_sha = enc.sha;   // but the SERVED bytes are right here
          justEncoded = true;
          if (VERBOSE) console.log(`    photo ${key}: migrated legacy ${from} -> ${enc.w}x${enc.h} webp`);
        } else {
          heldEntry.photo_file = null; heldEntry.has_photo = false;
        }
      } else if (heldEntry.photo_file && !existsSync(join(PHOTO_DIR, `${key}.webp`))) {
        heldEntry.photo_file = null; heldEntry.has_photo = false;
      }

      // A held entry's picture is not re-read from a deck, but the file on disk
      // is still the file the visitor downloads, so its stamp is taken the same
      // way everyone else's is. Skipped when the bytes were just made above and
      // are still only in memory — photoFileStamp would read the old file.
      if (heldEntry.photo_file && !justEncoded) {
        const stamp = photoFileStamp(`${key}.webp`);
        if (stamp) { heldEntry.photo_bytes = stamp.bytes; heldEntry.photo_file_sha = stamp.sha; }
      } else if (!heldEntry.photo_file) {
        heldEntry.photo_file_sha = null;
      }
      heldEntry.photo_low_quality = !!heldEntry.photo_file &&
        isLowQualityPhoto(heldEntry.photo_w, heldEntry.photo_h);

      chefs.push(heldEntry);
      // Provenance survives the hold: if the districts map has no record (the
      // hand-made snapshot had none), recover the deck from the entry's own
      // region label so "which deck did this come from" is never lost.
      const heldDeck = DECKS.find((d) => d.key === (prevMeta && prevMeta.source_deck))
                    || DECKS.find((d) => d.label === heldEntry.region_deck) || null;
      chefs[chefs.length - 1].source_deck = heldDeck ? heldDeck.key : null;
      districts[key] = {
        district: label,
        district_short: shortLabel,
        source_deck: heldDeck ? heldDeck.key : null,
        source_url: heldDeck ? heldDeck.page : null,
        slide_title: heldEntry.slide_title || null,
        present_this_run: false,
        first_seen: (prevMeta && prevMeta.first_seen) || lastConfirmed,
        last_confirmed: lastConfirmed,
        last_changed: heldEntry.last_changed || lastConfirmed,
        days_since_confirmed: Math.round(ageDays * 10) / 10
      };
      held.push(`${label}: ${heldEntry.name} (${ageDays.toFixed(1)}d)`);
      continue;
    }

    // Either never seen, or past the cap. The FRAME stays — labelled, empty.
    if (prevChef && prevChef.name) {
      dropped.push(`${label}: ${prevChef.name} (` +
        (Number.isFinite(ageDays) ? `${ageDays.toFixed(1)}d` : 'never confirmed') + ')');
    }
    chefs.push({
      district: label,
      district_key: key,
      district_short: shortLabel,
      region_deck: null,
      slide_title: null,
      name: null,
      store_role: '',
      stats: [],
      writeup: '',
      is_xfinity: key === 'xfinity',
      is_store: false,
      vacant: true,
      has_photo: false,
      photo_file: null,
      photo_file_sha: null,
      photo_low_quality: false,
      last_confirmed: lastConfirmed,
      days_since_confirmed: Number.isFinite(ageDays) ? Math.round(ageDays * 10) / 10 : null,
      stale: false
    });
    districts[key] = {
      district: label,
      district_short: shortLabel,
      source_deck: (prevMeta && prevMeta.source_deck) || null,
      source_url: (prevMeta && prevMeta.source_url) || null,
      slide_title: null,
      present_this_run: false,
      first_seen: (prevMeta && prevMeta.first_seen) || null,
      last_confirmed: lastConfirmed,
      last_changed: (prevMeta && prevMeta.last_changed) || null,
      days_since_confirmed: Number.isFinite(ageDays) ? Math.round(ageDays * 10) / 10 : null
    };
  }

  /* -- 10d. the document ---------------------------------------------------- */
  const doc = {
    generated_at: started,
    generator: 'build/pull-headchefs.mjs',
    note: 'GENERATED FILE — do not hand-edit. Rebuilt from the Win-The-Weekend ' +
          'decks by .github/workflows/headchefs.yml every 30 minutes.',
    policy: {
      poll_minutes: 30,
      client_cadence: 'weekly, Fridays',
      hold_last_seen: true,
      stale_warn_days: STALE_WARN_DAYS,
      stale_drop_days: STALE_DROP_DAYS,
      why:
        'The decks are edited in place, so a district can be missing for minutes ' +
        'while the client rebuilds a slide. Blanking a frame on one absent read ' +
        'would make the wall flicker. So an absent district keeps the chef ' +
        'already on file and only the clock moves. The cap is ' + STALE_DROP_DAYS +
        ' days = two missed Friday postings: one skipped week is normal (holiday, ' +
        'manager out, deck rebuilt), two consecutive means the entry is no longer ' +
        '"last week\'s winner" but a fortnight-old photograph being presented as ' +
        'this week\'s — worse than an empty frame. Past the cap the chef is ' +
        'dropped and the frame goes back to a labelled empty mat. The frame and ' +
        'its engraved district label are never dropped.',
      photo: {
        max_w: PHOTO_MAX_W, max_h: PHOTO_MAX_H, format: 'webp', quality: PHOTO_QUALITY,
        why: 'Sized for the picture frames (~105 CSS px at 2560) and the narrow ' +
             'card strip (~172 CSS px at 390). The deck ships 1024x1536 JPEGs.'
      }
    },
    district_order: order,
    sources,
    districts,
    headchefs: chefs
  };

  /* -- 10e. write, atomically, only if something actually changed ---------- */
  const prevRaw = existsSync(OUT_JSON) ? readFileSync(OUT_JSON, 'utf8') : '';
  const nextRaw = JSON.stringify(doc, null, 2) + '\n';

  // `generated_at` and the per-run clocks move every run, so a raw diff is
  // always non-empty. Compare only what a visitor could see.
  //
  // `photo_file_sha`, `is_store` and `photo_low_quality` count as visible even
  // though the website does not read them yet: the first is the stamp that
  // decides whether a browser re-downloads a photograph whose filename never
  // changes, and the other two are the difference between a frame captioned
  // "Calumet City" reading as an award and reading as a mis-scrape. Leaving them
  // out would mean a photograph's served bytes changing with no commit to carry
  // it — the same silent staleness this file exists to prevent, one level down.
  const visible = (raw) => {
    try {
      const d = JSON.parse(raw);
      return JSON.stringify({
        order: d.district_order,
        chefs: (d.headchefs || []).map((c) => [
          c.district, c.district_short, c.name, c.store_role, c.writeup,
          c.stats, c.is_xfinity, c.photo_file, c.photo_w, c.photo_h, !!c.vacant,
          c.photo_file_sha || null, !!c.is_store, !!c.photo_low_quality
        ])
      });
    } catch { return null; }
  };
  const wallChanged = visible(prevRaw) !== visible(nextRaw);

  /* orphan photos: a district that lost its chef, or a chef that lost a photo */
  const keep = new Set(chefs.filter((c) => c.photo_file).map((c) => c.photo_file.replace(/^photos\//, '')));
  let orphans = [];
  try {
    orphans = readdirSync(PHOTO_DIR).filter((n) => !keep.has(n) && !n.startsWith('.'));
  } catch { orphans = []; }

  /* ── NO RUN MAY DELETE MORE PHOTOGRAPHS THAN IT WRITES ────────────────────
   * The orphan sweep is housekeeping: a district that dropped past the stale
   * cap, or a legacy filename replaced by this script's own. Housekeeping is
   * one file at a time. When it is suddenly SIX files at once and this run has
   * written none, that is not housekeeping — it is the deck having changed
   * shape underneath us and every chef losing their portrait in the same pass.
   * Reproduced 2026-09-01: an exporter change that stopped inlining photographs
   * deleted five committed portraits and published six faceless frames, exit 0.
   *
   * The photo failure in section 6 now stops that particular run long before it
   * gets here. This is the second lock on the same door, and it is the one that
   * covers the cases nobody has thought of yet, because it does not care WHY
   * the portraits became unreferenced. The rule is simply: a run may retire one
   * photograph on its own account, and beyond that it must have written at
   * least as many as it is removing.
   *
   * When the guard trips the files are KEPT. Unreferenced bytes in the repo are
   * harmless — nothing links to them — whereas a deleted portrait is gone, and
   * the deck may no longer be able to supply it. The JSON is still written: it
   * is correct, and blocking it would only add a second failure to the first.
   */
  const deleteAllowance = Math.max(1, photos.size);
  let orphansKept = [];
  if (orphans.length > deleteAllowance) {
    orphansKept = orphans;
    console.warn(
      `\n  ! REFUSING TO DELETE ${orphans.length} PHOTOGRAPHS: ${orphans.join(', ')}\n` +
      `    This run wrote ${photos.size} photo${photos.size === 1 ? '' : 's'}, so removing ` +
      `${orphans.length} is not tidying up after one district — it is every portrait becoming ` +
      `unreferenced at once, which means something upstream changed shape.\n` +
      `    The files have been LEFT ON DISK. They are unreferenced, so nothing on the wall ` +
      `points at them and they cost a visitor nothing; a deleted portrait, by contrast, cannot ` +
      `be got back if the deck has stopped carrying it.\n` +
      `    Check headchefs.json's headchefs[] for entries with has_photo:false. If the wall is ` +
      `right and these files really are finished with, delete them by hand — that is one ` +
      `deliberate commit, which is what a deletion should be.`);
    annotate('Refused to delete unreferenced photographs',
             `${orphans.length} photographs became unreferenced in a run that wrote ` +
             `${photos.size}. They have been left on disk rather than deleted: ` +
             `${orphans.join(', ')}. Check headchefs.json for entries with has_photo:false.`);
    orphans = [];
  }

  console.log('');
  console.log(`  districts on the wall : ${order.length} (${order.join(', ')})`);
  console.log(`  chefs present in deck : ${found.size}`);
  if (held.length)    console.log(`  held last-seen        : ${held.join('; ')}`);
  if (dropped.length) console.log(`  dropped past ${STALE_DROP_DAYS}d cap : ${dropped.join('; ')}`);
  if (changed.length) console.log(`  changed this run      : ${changed.join('; ')}`);
  if (photos.size)    console.log(`  photos re-encoded     : ${[...photos.keys()].join(', ')}`);
  if (orphans.length) console.log(`  orphan photos removed : ${orphans.join(', ')}`);
  if (orphansKept.length) console.log(`  orphan photos KEPT    : ${orphansKept.join(', ')} (see the refusal above)`);
  console.log(`  wall content changed  : ${wallChanged ? 'YES' : 'no'}`);

  /* ── AND NOW SAY IT SOMEWHERE SOMEBODY LOOKS ──────────────────────────────
   * Everything above is console.log on a job that is about to exit 0. On a
   * GitHub runner that is a collapsed log inside a green tick, and the two
   * lines that most need reading — which districts are showing LAST week's
   * winner, and which of those have gone stale — are the ones nobody ever
   * sees. Repeated as Actions annotations they land on the run summary, on the
   * commit, and in the Actions e-mail, without failing the job, which is the
   * right register: holding is correct behaviour, it just must not be silent.
   * Outside Actions `annotate` is a no-op and this changes nothing at all.   */
  for (const line of held) {
    annotate('Head chef held from a previous run',
             `${line} — this district was not in its deck on this run, so the frame is showing ` +
             `the chef already on file. It is dropped for a labelled empty mat at ` +
             `${STALE_DROP_DAYS} days.`);
  }
  for (const c of chefs) {
    if (!c.stale) continue;
    annotate(`${c.district}: stale head chef`,
             `${c.name} has not been confirmed in a deck for ${c.days_since_confirmed} days ` +
             `(warning at ${STALE_WARN_DAYS}, dropped at ${STALE_DROP_DAYS}). The wall is ` +
             `presenting a ${c.days_since_confirmed}-day-old winner as this week's.`);
  }

  if (DRY_RUN) {
    console.log('\n--dry-run: nothing written.');
    return { wallChanged, doc };
  }

  if (!wallChanged && !photos.size && !orphans.length) {
    // Refresh nothing. An unchanged wall must not produce a commit, and must not
    // even rewrite the file — the workflow decides on `git status`.
    console.log('\nNothing to write; headchefs.json left untouched.');
    return { wallChanged: false, doc };
  }

  mkdirSync(PHOTO_DIR, { recursive: true });
  const tmps = [];
  try {
    for (const [name, bytes] of photos) {
      const dest = join(PHOTO_DIR, name);
      const tmp = `${dest}.tmp`;
      writeFileSync(tmp, bytes);
      tmps.push([tmp, dest]);
    }
    const jsonTmp = `${OUT_JSON}.tmp`;
    writeFileSync(jsonTmp, nextRaw);
    tmps.push([jsonTmp, OUT_JSON]);

    // Only now does anything move into place.
    for (const [tmp, dest] of tmps) renameSync(tmp, dest);
    tmps.length = 0;
  } finally {
    for (const [tmp] of tmps) { try { if (existsSync(tmp)) unlinkSync(tmp); } catch {} }
  }

  for (const n of orphans) { try { unlinkSync(join(PHOTO_DIR, n)); } catch {} }

  const total = chefs.filter((c) => c.photo_file).reduce((a, c) => a + (Number(c.photo_bytes) || 0), 0);
  console.log(`\nWrote headchefs/headchefs.json (${nextRaw.length} bytes) and ` +
              `${keep.size} photo${keep.size === 1 ? '' : 's'} (${(total / 1024).toFixed(1)} KB total).`);
  return { wallChanged: true, doc };
}

run().then(() => process.exit(0)).catch((err) => {
  if (err instanceof PullError) {
    console.error(`\nFAILED: ${err.message}`);
  } else {
    console.error(`\nFAILED: unexpected error — ${err && err.stack ? err.stack : err}`);
  }
  console.error('headchefs.json and headchefs/photos/ were NOT modified.');
  process.exit(1);
});
