/* ---------------------------------------------------------------------------
 * 4. THE TINY HTML SHIM
 *    Not a parser — a tag-depth scanner. It knows one thing: given the index of
 *    a `<div`, where does its matching `</div>` end. That is enough to cut one
 *    slide (or one sub-block) out of a 5 MB document exactly, without pulling a
 *    dependency in and without the "read to the next sibling and hope" trick,
 *    which breaks the moment a slide nests another slide-classed element.
 * ------------------------------------------------------------------------ */

const VOID_TAGS = new Set(['img', 'br', 'hr', 'input', 'meta', 'link', 'source', 'area', 'col', 'wbr']);

/**
 * @param {string} html
 * @param {number} start index of the `<` that opens the element
 * @returns {{outer:string, inner:string, end:number, attrs:string}|null}
 */
function sliceElement(html, start) {
  const open = /^<([a-zA-Z][a-zA-Z0-9-]*)((?:"[^"]*"|'[^']*'|[^>"'])*)>/.exec(html.slice(start, start + 8192));
  if (!open) return null;
  const tag = open[1].toLowerCase();
  const attrs = open[2] || '';
  const innerStart = start + open[0].length;
  if (VOID_TAGS.has(tag) || /\/\s*$/.test(attrs)) {
    return { outer: open[0], inner: '', end: innerStart, attrs };
  }

  const re = new RegExp(`<(/?)${tag}\\b`, 'gi');
  re.lastIndex = innerStart;
  let depth = 1;
  let m;
  while ((m = re.exec(html))) {
    depth += m[1] ? -1 : 1;
    if (depth === 0) {
      const close = html.indexOf('>', m.index);
      if (close < 0) return null;
      return {
        outer: html.slice(start, close + 1),
        inner: html.slice(innerStart, m.index),
        end: close + 1,
        attrs
      };
    }
  }
  return null;   // unbalanced — caller treats this as a shape failure
}

/** First descendant element carrying `cls` in its class attribute. */
function findByClass(html, cls) {
  const re = new RegExp(`<([a-zA-Z][a-zA-Z0-9-]*)((?:"[^"]*"|'[^']*'|[^>"'])*?)class\\s*=\\s*"([^"]*)"`, 'g');
  let m;
  while ((m = re.exec(html))) {
    if (!new RegExp(`(^|\\s)${cls}(\\s|$)`).test(m[3])) continue;
    const el = sliceElement(html, m.index);
    if (el) return el;
  }
  return null;
}

/** Every descendant element carrying `cls`, in document order, non-overlapping. */
function findAllByClass(html, cls) {
  const out = [];
  let idx = 0;
  const re = new RegExp(`<([a-zA-Z][a-zA-Z0-9-]*)((?:"[^"]*"|'[^']*'|[^>"'])*?)class\\s*=\\s*"([^"]*)"`, 'g');
  let m;
  while ((m = re.exec(html))) {
    if (m.index < idx) continue;
    if (!new RegExp(`(^|\\s)${cls}(\\s|$)`).test(m[3])) continue;
    const el = sliceElement(html, m.index);
    if (!el) continue;
    out.push(el);
    idx = el.end;
    re.lastIndex = el.end;
  }
  return out;
}

/** First `<tag>` element's inner HTML. */
function firstTagInner(html, tag) {
  const re = new RegExp(`<${tag}\\b`, 'i');
  const m = re.exec(html);
  if (!m) return null;
  const el = sliceElement(html, m.index);
  return el ? el.inner : null;
}

/* ---------------------------------------------------------------------------
 * 5. DISTRICT DERIVATION
 * ------------------------------------------------------------------------ */

/**
 * Pull the district out of a slide title. THE TITLE IS THE SOURCE — there is no
 * list of districts anywhere in the extraction path.
 *
 *   "Head Chef Of The Week — Big South"      -> Big South
 *   "Head Chef Of The Week — Outlawz (East)" -> East Side   (ALIASES)
 *   "⭐ Xfinity Head Chef Of The Week"        -> Xfinity Head Chef of the Week
 *   "Head Chef Of The Week"                  -> the deck's own label
 *
 * @returns {{key:string, district:string, short:string}}
 */
function districtFromTitle(title, deck, isXfinity) {
  const clean = String(title || '')
    .replace(/^[^\p{L}\p{N}]+/u, '')       // leading ⭐, emoji, bullets
    .replace(/\s+/g, ' ')
    .trim();

  if (isXfinity || /xfinity/i.test(clean)) {
    return { key: 'xfinity', district: 'Xfinity Head Chef of the Week', short: 'Xfinity' };
  }

  // Everything after the LAST dash-family separator or colon is the district.
  const parts = clean.split(/\s*(?:[—–‒:|]|--|\s-\s)\s*/).filter(Boolean);
  let raw = parts.length > 1 ? parts[parts.length - 1] : '';

  // A trailing fragment that is just the award name again is not a district.
  if (!raw || /head\s+chef/i.test(raw)) raw = '';
  if (!raw) raw = deck.label;

  const rawSlug = slug(raw);
  const aliased = ALIASES.get(rawSlug);
  const district = aliased || titleCase(raw);
  return { key: slug(district), district, short: district };
}

/* ---------------------------------------------------------------------------
 * 6. SLIDE EXTRACTION
 * ------------------------------------------------------------------------ */

/**
 * Every head-chef slide in one deck.
 * Throws (PullError) on a slide whose shape we do not recognise — that is a
 * deck rewrite, and guessing at it is exactly how a half-file gets written.
 */
function extractSlides(html, deck) {
  // Sanity: is this even the deck? A redirect, a rate-limit page or an empty
  // file must not be read as "this deck has no head chefs this week".
  const slideCount = (html.match(/<div[^>]*\bclass\s*=\s*"[^"]*\bs\b[^"]*"/g) || []).length;
  if (slideCount < 3) {
    fail(`${deck.key}: fetched ${html.length} bytes but found only ${slideCount} slides — ` +
         `that is not the deck (redirect? rate limit? empty file?).`);
  }

  const out = [];
  const re = /<div\b((?:"[^"]*"|'[^']*'|[^>"'])*?)class\s*=\s*"([^"]*)"/g;
  let m;
  while ((m = re.exec(html))) {
    const cls = m[2];
    if (!/(^|\s)hcs(\s|$)/.test(cls)) continue;

    const el = sliceElement(html, m.index);
    if (!el) fail(`${deck.key}: an "hcs" slide at offset ${m.index} does not close — deck shape changed.`);
    re.lastIndex = el.end;

    const slide = el.inner;
    const isXfinity = /(^|\s)xfin(\s|$)/.test(cls);

    /* -- title (and therefore the district) -- */
    const hd = findByClass(slide, 'hd');
    const titleHtml = firstTagInner(hd ? hd.inner : slide, 'h2');
    const title = toText(titleHtml, false);
    if (!title) {
      fail(`${deck.key}: head-chef slide ${out.length} has no <h2> title — deck shape changed. ` +
           `Cannot derive its district, so nothing is written.`);
    }

    /* -- identity -- */
    const hcr = findByClass(slide, 'hcr');
    const scope = hcr ? hcr.inner : slide;
    const name = toText(firstTagInner(scope, 'h3'), false);
    if (!name) {
      fail(`${deck.key}: head-chef slide "${title}" has no <h3> name — deck shape changed.`);
    }
    const hsb = findByClass(scope, 'hsb');
    const storeRole = hsb ? toText(hsb.inner, false) : '';

    /* -- stats: whatever pairs the slide carries, in slide order -- */
    const stats = [];
    const hsg = findByClass(scope, 'hsg');
    for (const st of findAllByClass(hsg ? hsg.inner : scope, 'hst')) {
      const hv = findByClass(st.inner, 'hv');
      const hl = findByClass(st.inner, 'hl');
      const value = hv ? toText(hv.inner, false) : '';
      const label = hl ? toText(hl.inner, false) : '';
      if (value || label) stats.push({ value, label });
    }

    /* -- the write-up, newlines intact -- */
    const hcw = findByClass(scope, 'hcw');
    const writeup = hcw ? toText(hcw.inner, true) : '';

    /* -- the photograph -- */
    const photo = extractPhoto(slide);

    out.push({
      deck: deck.key,
      deckLabel: deck.label,
      slideIndex: out.length,
      slideTitle: title,
      isXfinity,
      name,
      storeRole,
      stats,
      writeup,
      photo,
      district: districtFromTitle(title, deck, isXfinity)
    });
  }

  return out;
}

/**
 * The slide carries the same picture twice: `img.hcfg` is the sharp foreground
 * and `.hcbg` the blurred fill behind it. Prefer the foreground; fall back to
 * the background so a slide built without the <img> still yields a face.
 * @returns {{buf:Buffer, mime:string, sha:string}|null}
 */
function extractPhoto(slide) {
  const hcp = findByClass(slide, 'hcp');
  const scope = hcp ? hcp.outer : slide;

  const fg = /<img\b[^>]*\bclass\s*=\s*"[^"]*\bhcfg\b[^"]*"[^>]*\bsrc\s*=\s*"(data:image\/([a-z+]+);base64,([A-Za-z0-9+/=\s]+))"/i.exec(scope)
          || /<img\b[^>]*\bsrc\s*=\s*"(data:image\/([a-z+]+);base64,([A-Za-z0-9+/=\s]+))"[^>]*\bclass\s*=\s*"[^"]*\bhcfg\b/i.exec(scope);
  const bg = /background-image\s*:\s*url\(\s*(?:&quot;|["'])?data:image\/([a-z+]+);base64,([A-Za-z0-9+/=\s]+?)(?:&quot;|["'])?\s*\)/i.exec(scope);

  let mime = null; let b64 = null;
  if (fg) { mime = fg[2]; b64 = fg[3]; }
  else if (bg) { mime = bg[1]; b64 = bg[2]; }
  if (!b64) return null;

  let buf;
  try { buf = Buffer.from(b64.replace(/\s+/g, ''), 'base64'); } catch { return null; }
  if (!buf || buf.length < 512) return null;              // not a photograph
  return { buf, mime: `image/${mime}`, sha: sha256(buf) };
}

/* ---------------------------------------------------------------------------
 * 7. NETWORK
 * ------------------------------------------------------------------------ */

async function fetchDeck(deck) {
  let lastErr = null;
  for (let attempt = 1; attempt <= FETCH_ATTEMPTS; attempt++) {
    const ctl = new AbortController();
    const timer = setTimeout(() => ctl.abort(), FETCH_TIMEOUT_MS);
    try {
      const res = await fetch(deck.raw, {
        signal: ctl.signal,
        redirect: 'follow',
        headers: { 'user-agent': 'ccc-headchefs-bot', 'accept': 'text/html,text/plain' }
      });
      if (!res.ok) throw new Error(`HTTP ${res.status} ${res.statusText}`);
      const text = await res.text();
      if (!text || text.length < 4096) throw new Error(`response was ${text.length} bytes`);
      clearTimeout(timer);
      return text;
    } catch (err) {
      lastErr = err;
      if (VERBOSE) console.error(`  attempt ${attempt}/${FETCH_ATTEMPTS} failed: ${err.message}`);
    } finally {
      clearTimeout(timer);
    }
  }
  fail(`${deck.key}: could not read ${deck.raw} — ${lastErr && lastErr.message}. ` +
       `Nothing written; headchefs.json is unchanged.`);
}

