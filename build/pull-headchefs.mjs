#!/usr/bin/env node
/* =============================================================================
 * Cook County Cooks — build/pull-headchefs.mjs
 * RE-READ THE WIN-THE-WEEKEND DECKS AND REBUILD headchefs/headchefs.json
 * -----------------------------------------------------------------------------
 * THE BUG THIS EXISTS TO KILL
 *   headchefs/headchefs.json was a hand-made snapshot taken on 2026-08-26 and
 *   never refreshed. The client updated his Big South deck, the break-room wall
 *   did not change, and nothing in the site was even capable of noticing —
 *   because nothing re-read the decks. He expects the wall to follow the decks.
 *
 * WHY IT RUNS HERE AND NOT IN THE BROWSER
 *   The Big South deck is a 4.97 MB single-file HTML with the photographs
 *   inlined as base64 data URIs. Fetching that from the page would put five
 *   megabytes of deck on every visitor — on a phone build that is already
 *   fighting a memory ceiling. So the decks are read HERE, on a GitHub runner
 *   (.github/workflows/headchefs.yml, every 30 minutes), the result is committed,
 *   and the visitor downloads one ~10 KB JSON file and a handful of ~30 KB
 *   photographs sized for the picture frames they land in.
 *
 * NO DEPENDENCIES
 *   Stock Node (fetch, node:fs, node:crypto, node:child_process) and nothing
 *   else. There is no HTML parser in Node and adding one would mean adding an
 *   npm dependency to a repo that has none, so THE EXTRACTION IS DONE WITH
 *   REGEX PLUS A TINY TAG-DEPTH SCANNER (`sliceElement` below) rather than a DOM.
 *   That is a deliberate trade and it is safe here for one specific reason: the
 *   decks are machine-generated by one exporter, every head-chef slide is the
 *   same shape, and the moment that shape changes this script FAILS LOUDLY
 *   instead of writing a half-file (see "SHAPE" below).
 *
 *   The one external tool is ImageMagick, for the photo re-encode. It ships on
 *   every GitHub `ubuntu-*` runner. If it is missing AND a photo actually needs
 *   encoding, the run aborts rather than committing a 312 KB JPEG into a picture
 *   frame that is 105 px wide.
 *
 * THE DECK SHAPE (verified against both live decks 2026-08-28)
 *   <div class="s hcs a">                     one head-chef slide ("hcs")
 *     <div class="hd"><h2>Head Chef Of The Week — Big South</h2></div>
 *     <div class="hcc">
 *       <div class="hcp">
 *         <div class="hcbg" style="background-image:url("data:image/jpeg;base64,…")">
 *         <img class="hcfg" src="data:image/jpeg;base64,…">
 *       </div>
 *       <div class="hcr">
 *         <h3>Demarcus McKamey</h3>
 *         <div class="hsb">South Knoxville • Assistant Manager/Team Lead</div>
 *         <div class="hsg">
 *           <div class="hst"><div class="hv">$22,879</div><div class="hl">GP $</div></div> …
 *         </div>
 *         <div class="hcw">…the write-up, newline separated…</div>
 *   The Xfinity award is the same slide with `xfin` added to the slide class.
 *
 * DISTRICTS COME FROM THE SLIDE TITLES, NOT FROM A LIST
 *   `Head Chef Of The Week — Big South` -> "Big South". The text after the dash
 *   IS the district, whatever it says, so a renamed district follows by itself.
 *   ALIASES below is cosmetic only — it maps the deck's own wording onto the
 *   client's short label ("Outlawz (East)" -> "East Side") and an unknown
 *   district passes straight through, title-cased. Extraction never consults it
 *   to decide whether a slide counts.
 *
 * HOLD LAST-SEEN
 *   A district missing from its deck this run KEEPS the chef already on file.
 *   The client posts on Fridays and edits decks in place, so "absent right now"
 *   usually means "mid-update", not "nobody won". See STALE_DROP_DAYS.
 *
 * FAIL-SOFT AND ATOMIC
 *   Every deck must fetch and parse before anything is written. A 404, a
 *   timeout, or a slide whose shape we do not recognise aborts the whole run:
 *   headchefs.json and headchefs/photos/ are left exactly as they were and the
 *   process exits non-zero with a message that says which deck and why. Writes
 *   go to `.tmp` files and are renamed into place at the very end.
 *
 * USAGE
 *   node build/pull-headchefs.mjs              # fetch, extract, write
 *   node build/pull-headchefs.mjs --dry-run    # everything except the writes
 *   node build/pull-headchefs.mjs --verbose    # per-slide extraction report
 * ========================================================================== */

