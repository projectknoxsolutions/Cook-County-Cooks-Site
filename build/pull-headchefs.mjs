let imBinary;   // resolved lazily so a run that re-encodes nothing needs no IM

function imagemagick() {
  if (imBinary !== undefined) return imBinary;
  for (const [bin, pre] of [['magick', ['convert']], ['convert', []]]) {
    const r = spawnSync(bin, [...pre, '-version'], { encoding: 'utf8' });
    if (!r.error && r.status === 0) { imBinary = { bin, pre }; return imBinary; }
  }
  imBinary = null;
  return null;
}

/**
 * Re-encode one deck photograph down to the frame it lands in.
 * @returns {{bytes:Buffer, w:number, h:number}}
 */
function encodePhoto(srcBuf, key) {
  const im = imagemagick();
  if (!im) {
    fail(`ImageMagick not found, and "${key}" needs its photograph re-encoded. ` +
         `A 1024x1536 deck JPEG must never be committed straight into a picture ` +
         `frame ~105px wide. Install imagemagick (every GitHub ubuntu runner has ` +
         `it) or run with the photo already on disk. Nothing written.`);
  }
  const tmpIn  = join(tmpdir(), `ccc-hc-${process.pid}-${key}.src`);
  const tmpOut = join(tmpdir(), `ccc-hc-${process.pid}-${key}.webp`);
  try {
    writeFileSync(tmpIn, srcBuf);
    const args = [
      ...im.pre, tmpIn,
      '-auto-orient',
      '-strip',                                    // EXIF, GPS, colour profiles
      '-resize', `${PHOTO_MAX_W}x${PHOTO_MAX_H}>`, // shrink only, keep aspect
      '-quality', String(PHOTO_QUALITY),
      '-define', 'webp:method=6',
      tmpOut
    ];
    const r = spawnSync(im.bin, args, { encoding: 'utf8' });
    if (r.error || r.status !== 0 || !existsSync(tmpOut)) {
      fail(`${key}: photo re-encode failed — ${(r.stderr || (r.error && r.error.message) || 'unknown').trim()}`);
    }
    const bytes = readFileSync(tmpOut);

    // `convert <file> -format '%w %h' info:` works on ImageMagick 6 and 7 alike,
    // so the dimensions come back without needing a second binary on PATH.
    const id = spawnSync(im.bin, [...im.pre, tmpOut, '-format', '%w %h', 'info:'], { encoding: 'utf8' });
    let w = 0; let h = 0;
    if (!id.error && id.status === 0) {
      const parts = String(id.stdout).trim().split(/\s+/);
      w = Number(parts[0]) || 0; h = Number(parts[1]) || 0;
    }
    if (!w || !h) fail(`${key}: could not read the re-encoded photo's dimensions.`);
    return { bytes, w, h };
  } finally {
    for (const f of [tmpIn, tmpOut]) { try { if (existsSync(f)) unlinkSync(f); } catch {} }
  }
}

/* ---------------------------------------------------------------------------
 * 9. THE PREVIOUS FILE
 * ------------------------------------------------------------------------ */

function readPrevious() {
  const empty = { districtOrder: [], districts: {}, chefs: {} };
  if (!existsSync(OUT_JSON)) return empty;
  let doc;
  try { doc = JSON.parse(readFileSync(OUT_JSON, 'utf8')); }
  catch (err) {
    console.warn(`! headchefs.json is not valid JSON (${err.message}); rebuilding from the decks.`);
    return empty;
  }
  const districts = (doc && doc.districts) || {};
  const chefs = {};
  for (const c of (doc && Array.isArray(doc.headchefs) ? doc.headchefs : [])) {
    // Tolerate the hand-made 2026-08-26 snapshot, which had no district keys:
    // re-derive one from its slide_title so its entries can be held over.
    let key = c && c.district_key;
    if (!key && c && c.slide_title) {
      const deck = DECKS.find((d) => d.label === c.region_deck) || DECKS[0];
      key = districtFromTitle(c.slide_title, deck, !!c.is_xfinity).key;
    }
    if (key) chefs[key] = c;
  }
  const order = Array.isArray(doc && doc.district_order) && doc.district_order.length
    ? doc.district_order.slice()
    : [];
  // MIGRATION. The hand-made 2026-08-26 snapshot carried no per-entry clocks, so
  // every held entry would read as infinitely old and be dropped on the first
  // run — blanking frames on the very run that was supposed to stop that. The
  // document's own `generated_at` is when those entries were last confirmed.
  const fileStamp = (doc && doc.generated_at) || null;
  if (fileStamp) {
    for (const c of Object.values(chefs)) if (!c.last_confirmed) c.last_confirmed = fileStamp;
    for (const d of Object.values(districts)) if (!d.last_confirmed) d.last_confirmed = fileStamp;
  }
  return { districtOrder: order, districts, chefs };
}

/** Everything that decides whether an entry actually CHANGED. */
function contentFingerprint(chef) {
  return sha256(Buffer.from(JSON.stringify([
    chef.name, chef.store_role, chef.writeup, chef.stats,
    chef.is_xfinity, chef.slide_title, chef.photo_sha || null
  ]), 'utf8'));
}

/* ---------------------------------------------------------------------------
 * 10. THE RUN
 * ------------------------------------------------------------------------ */

async function run() {
  const started = nowIso();
  const prev = readPrevious();

  /* -- 10a. read every deck BEFORE deciding anything ----------------------- */
  const sources = [];
  const found = new Map();        // district key -> slide

  for (const deck of DECKS) {
    process.stdout.write(`· ${deck.key}: fetching ${deck.raw}\n`);
    const html = await fetchDeck(deck);
    const slides = extractSlides(html, deck);
    process.stdout.write(
      `  ${(html.length / 1048576).toFixed(2)} MB, ${slides.length} head-chef slide` +
      `${slides.length === 1 ? '' : 's'}${slides.length ? ': ' + slides.map((s) => `${s.district.district} / ${s.name}`).join(', ') : ''}\n`);

    for (const s of slides) {
      if (found.has(s.district.key)) {
        // Two slides claiming one district: the LAST one in the deck wins, which
        // is how these decks are edited (a new slide appended, the old left in).
        console.warn(`  ! two slides for "${s.district.district}" in ${deck.key}; ` +
                     `using the later one (${s.name}).`);
      }
      found.set(s.district.key, s);
      if (VERBOSE) {
        console.log(`    title="${s.slideTitle}" district="${s.district.district}" ` +
                    `name="${s.name}" role="${s.storeRole}" stats=${s.stats.length} ` +
                    `writeup=${s.writeup.length}ch photo=${s.photo ? s.photo.buf.length + 'B' : 'none'}`);
      }
    }

    sources.push({
      deck: deck.key,
      label: deck.label,
      page: deck.page,
      raw: deck.raw,
      fetched_at: nowIso(),
      bytes: html.length,
      head_chef_slides: slides.length,
      districts: slides.map((s) => s.district.district)
    });
  }

  /* -- 10b. the roster: persisted order, seeded once, extended by the decks - */
  const order = prev.districtOrder.slice();
  if (!order.length) for (const s of SEED_ROSTER) order.push(s.key);
  for (const key of found.keys()) if (!order.includes(key)) order.push(key);

  const seedByKey = new Map(SEED_ROSTER.map((s) => [s.key, s]));

  /* -- 10c. build one entry per district in the roster --------------------- */
  const now = Date.now();
  const chefs = [];
  const districts = {};
  const photos = new Map();       // filename -> Buffer, staged, written at the end
  const dropped = [];
  const held = [];
  const changed = [];

  for (const key of order) {
    const slide = found.get(key);
    const prevChef = prev.chefs[key] || null;
    const prevMeta = prev.districts[key] || null;

    /* --- present in a deck right now ------------------------------------ */
    if (slide) {
      const photoName = slide.photo ? `${key}.webp` : null;
      let photoFile = null; let photoW = 0; let photoH = 0; let photoBytes = 0;
      let photoSha = null;

      if (slide.photo) {
        photoSha = slide.photo.sha;
        const onDisk = existsSync(join(PHOTO_DIR, photoName));
        const sameSource = prevChef && prevChef.photo_sha === photoSha && onDisk;
        if (sameSource) {
          // Byte-identical source and the file is already there. Do NOT
          // re-encode: two ImageMagick builds do not produce identical bytes,
          // and a re-encode every 30 minutes would be a commit every 30 minutes
          // for a photograph nobody changed.
          photoFile = `photos/${photoName}`;
          photoW = Number(prevChef.photo_w) || 0;
          photoH = Number(prevChef.photo_h) || 0;
          try { photoBytes = statSync(join(PHOTO_DIR, photoName)).size; } catch { photoBytes = 0; }
        } else {
          const enc = encodePhoto(slide.photo.buf, key);
          photos.set(photoName, enc.bytes);
          photoFile = `photos/${photoName}`;
          photoW = enc.w; photoH = enc.h; photoBytes = enc.bytes.length;
          if (VERBOSE) {
            console.log(`    photo ${key}: ${slide.photo.buf.length}B source -> ` +
                        `${enc.bytes.length}B webp ${enc.w}x${enc.h}`);
          }
        }
      }

      const entry = {
        district: slide.district.district,
        district_key: key,
        district_short: slide.district.short,
        region_deck: slide.deckLabel,
        slide_title: slide.slideTitle,
        slide_index: slide.slideIndex,
        name: slide.name,
        store_role: slide.storeRole,
        stats: slide.stats,
        writeup: slide.writeup,
        is_xfinity: slide.isXfinity,
        vacant: false,
        has_photo: !!photoFile,
        photo_file: photoFile,
        photo_w: photoW,
        photo_h: photoH,
        photo_bytes: photoBytes,
        photo_sha: photoSha
      };

      const fp = contentFingerprint(entry);
      const prevFp = prevChef ? contentFingerprint(prevChef) : null;
      entry.last_confirmed = started;
      entry.last_changed = (prevChef && prevFp === fp && prevChef.last_changed)
        ? prevChef.last_changed
        : started;
      entry.days_since_confirmed = 0;
      entry.stale = false;
      if (prevFp !== fp) changed.push(`${entry.district}: ${entry.name}`);

      chefs.push(entry);
      districts[key] = {
        district: entry.district,
        district_short: entry.district_short,
        source_deck: slide.deck,
        source_url: DECKS.find((d) => d.key === slide.deck).page,
        slide_title: entry.slide_title,
        present_this_run: true,
        first_seen: (prevMeta && prevMeta.first_seen) || started,
        last_confirmed: started,
        last_changed: entry.last_changed,
        days_since_confirmed: 0
      };
      continue;
    }

    /* --- absent from every deck this run -------------------------------- */
    const label = (prevChef && prevChef.district) || (prevMeta && prevMeta.district)
                || (seedByKey.get(key) && seedByKey.get(key).district) || titleCase(key.replace(/-/g, ' '));
    const shortLabel = (prevChef && prevChef.district_short) || (prevMeta && prevMeta.district_short)
                || (seedByKey.get(key) && seedByKey.get(key).short) || label;

    const lastConfirmed = (prevChef && prevChef.last_confirmed)
                       || (prevMeta && prevMeta.last_confirmed) || null;
    const ageDays = lastConfirmed ? (now - Date.parse(lastConfirmed)) / DAY_MS : Infinity;

    if (prevChef && prevChef.name && ageDays <= STALE_DROP_DAYS) {
      // HOLD LAST-SEEN. The chef stays on the wall; only the clock moves.
      const heldEntry = Object.assign({}, prevChef, {
        district: label,
        district_key: key,
        district_short: shortLabel,
        vacant: false,
        days_since_confirmed: Math.round(ageDays * 10) / 10,
        stale: ageDays >= STALE_WARN_DAYS,
        last_confirmed: lastConfirmed,
        last_changed: prevChef.last_changed || lastConfirmed
      });

      /* LEGACY PHOTO MIGRATION. A held entry can still be pointing at a photo
         from the hand-made snapshot — an un-resized JPEG under a name this
         script does not own (e.g. photos/chicago-3.jpg, 43 KB). We no longer
         have its slide, but we have the file, so it is re-encoded from disk
         into this district's own photos/<key>.webp and brought inside the byte
         budget. Runs once: after the first migration the name already matches
         and nothing happens. */
      const want = `photos/${key}.webp`;
      if (heldEntry.photo_file && heldEntry.photo_file !== want) {
        const from = join(PHOTO_DIR, String(heldEntry.photo_file).replace(/^photos\//, ''));
        if (existsSync(from)) {
          const enc = encodePhoto(readFileSync(from), key);
          photos.set(`${key}.webp`, enc.bytes);
          heldEntry.photo_file = want;
          heldEntry.photo_w = enc.w; heldEntry.photo_h = enc.h;
          heldEntry.photo_bytes = enc.bytes.length;
          heldEntry.photo_sha = null;   // the deck source is gone; nothing to match
          if (VERBOSE) console.log(`    photo ${key}: migrated legacy ${from} -> ${enc.w}x${enc.h} webp`);
        } else {
          heldEntry.photo_file = null; heldEntry.has_photo = false;
        }
      } else if (heldEntry.photo_file && !existsSync(join(PHOTO_DIR, `${key}.webp`))) {
        heldEntry.photo_file = null; heldEntry.has_photo = false;
      }
      chefs.push(heldEntry);
      // Provenance survives the hold: if the districts map has no record (the
      // hand-made snapshot had none), recover the deck from the entry's own
      // region label so "which deck did this come from" is never lost.
      const heldDeck = DECKS.find((d) => d.key === (prevMeta && prevMeta.source_deck))
                    || DECKS.find((d) => d.label === heldEntry.region_deck) || null;
      chefs[chefs.length - 1].source_deck = heldDeck ? heldDeck.key : null;
      districts[key] = {
        district: label,
        district_short: shortLabel,
        source_deck: heldDeck ? heldDeck.key : null,
        source_url: heldDeck ? heldDeck.page : null,
        slide_title: heldEntry.slide_title || null,
        present_this_run: false,
        first_seen: (prevMeta && prevMeta.first_seen) || lastConfirmed,
        last_confirmed: lastConfirmed,
        last_changed: heldEntry.last_changed || lastConfirmed,
        days_since_confirmed: Math.round(ageDays * 10) / 10
      };
      held.push(`${label}: ${heldEntry.name} (${ageDays.toFixed(1)}d)`);
      continue;
    }

    // Either never seen, or past the cap. The FRAME stays — labelled, empty.
    if (prevChef && prevChef.name) {
      dropped.push(`${label}: ${prevChef.name} (` +
        (Number.isFinite(ageDays) ? `${ageDays.toFixed(1)}d` : 'never confirmed') + ')');
    }
    chefs.push({
      district: label,
      district_key: key,
      district_short: shortLabel,
      region_deck: null,
      slide_title: null,
      name: null,
      store_role: '',
      stats: [],
      writeup: '',
      is_xfinity: key === 'xfinity',
      vacant: true,
      has_photo: false,
      photo_file: null,
      last_confirmed: lastConfirmed,
      days_since_confirmed: Number.isFinite(ageDays) ? Math.round(ageDays * 10) / 10 : null,
      stale: false
    });
    districts[key] = {
      district: label,
      district_short: shortLabel,
      source_deck: (prevMeta && prevMeta.source_deck) || null,
      source_url: (prevMeta && prevMeta.source_url) || null,
      slide_title: null,
      present_this_run: false,
      first_seen: (prevMeta && prevMeta.first_seen) || null,
      last_confirmed: lastConfirmed,
      last_changed: (prevMeta && prevMeta.last_changed) || null,
      days_since_confirmed: Number.isFinite(ageDays) ? Math.round(ageDays * 10) / 10 : null
    };
  }

  /* -- 10d. the document ---------------------------------------------------- */
  const doc = {
    generated_at: started,
    generator: 'build/pull-headchefs.mjs',
    note: 'GENERATED FILE — do not hand-edit. Rebuilt from the Win-The-Weekend ' +
          'decks by .github/workflows/headchefs.yml every 30 minutes.',
    policy: {
      poll_minutes: 30,
      client_cadence: 'weekly, Fridays',
      hold_last_seen: true,
      stale_warn_days: STALE_WARN_DAYS,
      stale_drop_days: STALE_DROP_DAYS,
      why:
        'The decks are edited in place, so a district can be missing for minutes ' +
        'while the client rebuilds a slide. Blanking a frame on one absent read ' +
        'would make the wall flicker. So an absent district keeps the chef ' +
        'already on file and only the clock moves. The cap is ' + STALE_DROP_DAYS +
        ' days = two missed Friday postings: one skipped week is normal (holiday, ' +
        'manager out, deck rebuilt), two consecutive means the entry is no longer ' +
        '"last week\'s winner" but a fortnight-old photograph being presented as ' +
        'this week\'s — worse than an empty frame. Past the cap the chef is ' +
        'dropped and the frame goes back to a labelled empty mat. The frame and ' +
        'its engraved district label are never dropped.',
      photo: {
        max_w: PHOTO_MAX_W, max_h: PHOTO_MAX_H, format: 'webp', quality: PHOTO_QUALITY,
        why: 'Sized for the picture frames (~105 CSS px at 2560) and the narrow ' +
             'card strip (~172 CSS px at 390). The deck ships 1024x1536 JPEGs.'
      }
    },
    district_order: order,
    sources,
    districts,
    headchefs: chefs
  };

  /* -- 10e. write, atomically, only if something actually changed ---------- */
  const prevRaw = existsSync(OUT_JSON) ? readFileSync(OUT_JSON, 'utf8') : '';
  const nextRaw = JSON.stringify(doc, null, 2) + '\n';

  // `generated_at` and the per-run clocks move every run, so a raw diff is
  // always non-empty. Compare only what a visitor could see.
  const visible = (raw) => {
    try {
      const d = JSON.parse(raw);
      return JSON.stringify({
        order: d.district_order,
        chefs: (d.headchefs || []).map((c) => [
          c.district, c.district_short, c.name, c.store_role, c.writeup,
          c.stats, c.is_xfinity, c.photo_file, c.photo_w, c.photo_h, !!c.vacant
        ])
      });
    } catch { return null; }
  };
  const wallChanged = visible(prevRaw) !== visible(nextRaw);

  /* orphan photos: a district that lost its chef, or a chef that lost a photo */
  const keep = new Set(chefs.filter((c) => c.photo_file).map((c) => c.photo_file.replace(/^photos\//, '')));
  let orphans = [];
  try {
    orphans = readdirSync(PHOTO_DIR).filter((n) => !keep.has(n) && !n.startsWith('.'));
  } catch { orphans = []; }

  console.log('');
  console.log(`  districts on the wall : ${order.length} (${order.join(', ')})`);
  console.log(`  chefs present in deck : ${found.size}`);
  if (held.length)    console.log(`  held last-seen        : ${held.join('; ')}`);
  if (dropped.length) console.log(`  dropped past ${STALE_DROP_DAYS}d cap : ${dropped.join('; ')}`);
  if (changed.length) console.log(`  changed this run      : ${changed.join('; ')}`);
  if (photos.size)    console.log(`  photos re-encoded     : ${[...photos.keys()].join(', ')}`);
  if (orphans.length) console.log(`  orphan photos removed : ${orphans.join(', ')}`);
  console.log(`  wall content changed  : ${wallChanged ? 'YES' : 'no'}`);

  if (DRY_RUN) {
    console.log('\n--dry-run: nothing written.');
    return { wallChanged, doc };
  }

  if (!wallChanged && !photos.size && !orphans.length) {
    // Refresh nothing. An unchanged wall must not produce a commit, and must not
    // even rewrite the file — the workflow decides on `git status`.
    console.log('\nNothing to write; headchefs.json left untouched.');
    return { wallChanged: false, doc };
  }

  mkdirSync(PHOTO_DIR, { recursive: true });
  const tmps = [];
  try {
    for (const [name, bytes] of photos) {
      const dest = join(PHOTO_DIR, name);
      const tmp = `${dest}.tmp`;
      writeFileSync(tmp, bytes);
      tmps.push([tmp, dest]);
    }
    const jsonTmp = `${OUT_JSON}.tmp`;
    writeFileSync(jsonTmp, nextRaw);
    tmps.push([jsonTmp, OUT_JSON]);

    // Only now does anything move into place.
    for (const [tmp, dest] of tmps) renameSync(tmp, dest);
    tmps.length = 0;
  } finally {
    for (const [tmp] of tmps) { try { if (existsSync(tmp)) unlinkSync(tmp); } catch {} }
  }

  for (const n of orphans) { try { unlinkSync(join(PHOTO_DIR, n)); } catch {} }

  const total = chefs.filter((c) => c.photo_file).reduce((a, c) => a + (Number(c.photo_bytes) || 0), 0);
  console.log(`\nWrote headchefs/headchefs.json (${nextRaw.length} bytes) and ` +
              `${keep.size} photo${keep.size === 1 ? '' : 's'} (${(total / 1024).toFixed(1)} KB total).`);
  return { wallChanged: true, doc };
}

run().then(() => process.exit(0)).catch((err) => {
  if (err instanceof PullError) {
    console.error(`\nFAILED: ${err.message}`);
  } else {
    console.error(`\nFAILED: unexpected error — ${err && err.stack ? err.stack : err}`);
  }
  console.error('headchefs.json and headchefs/photos/ were NOT modified.');
  process.exit(1);
});
