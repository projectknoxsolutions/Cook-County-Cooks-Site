const NAMED_ENTITIES = {
  amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ',
  mdash: '—', ndash: '–', hellip: '…', bull: '•',
  middot: '·', lsquo: '‘', rsquo: '’', ldquo: '“',
  rdquo: '”', deg: '°', trade: '™', reg: '®',
  copy: '©', times: '×', star: '★', dollar: '$'
};

/** Decode the entity flavours a slide exporter actually emits. */
function decodeEntities(s) {
  return String(s).replace(/&(#x?[0-9a-fA-F]+|[a-zA-Z][a-zA-Z0-9]*);/g, (m, body) => {
    if (body.charAt(0) === '#') {
      const cp = body.charAt(1) === 'x' || body.charAt(1) === 'X'
        ? parseInt(body.slice(2), 16)
        : parseInt(body.slice(1), 10);
      return Number.isFinite(cp) && cp > 0 && cp <= 0x10ffff ? String.fromCodePoint(cp) : m;
    }
    const v = NAMED_ENTITIES[body.toLowerCase()];
    return v === undefined ? m : v;
  });
}

/**
 * Inner HTML -> plain text.
 * `keepBreaks` preserves paragraph structure: <br> and block ends become \n,
 * which is what the write-up needs (chefwall.js's normaliseWriteup splits on
 * newlines to decide bullets vs prose). Everything else collapses to one line.
 */
function toText(html, keepBreaks) {
  let s = String(html == null ? '' : html);
  s = s.replace(/<!--[\s\S]*?-->/g, '');
  s = s.replace(/<(script|style)\b[^>]*>[\s\S]*?<\/\1>/gi, '');
  if (keepBreaks) {
    s = s.replace(/<br\s*\/?>/gi, '\n');
    s = s.replace(/<\/(p|div|li|h[1-6]|tr)\s*>/gi, '\n');
  }
  s = s.replace(/<[^>]*>/g, keepBreaks ? '' : ' ');
  s = decodeEntities(s);
  s = s.replace(/\r\n?/g, '\n');
  if (keepBreaks) {
    return s.split('\n').map((l) => l.replace(/[^\S\n]+/g, ' ').trim())
      .join('\n').replace(/\n{3,}/g, '\n\n').trim();
  }
  return s.replace(/\s+/g, ' ').trim();
}

/** "The South Side!" -> "the-south-side" */
function slug(s) {
  return String(s == null ? '' : s)
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

/** Title Case, but leaves an already-mixed-case word alone ("McKamey"). */
function titleCase(s) {
  return String(s).split(/\s+/).map((w) => {
    if (!w) return w;
    if (/[a-z]/.test(w) && /[A-Z]/.test(w.slice(1))) return w;   // McKamey, iPhone
    return w.charAt(0).toUpperCase() + w.slice(1);
  }).join(' ');
}

function sha256(buf) { return createHash('sha256').update(buf).digest('hex'); }

